void a2e_video_init(a2e_video *v) {
    memset(v, 0, sizeof(*v));
    v->dirty = true;
}

u16 a2e_rgb_to_565(u8 r, u8 g, u8 b) {
    return (u16)(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

void a2e_rgb565_byteswap(u16 *buf, size_t count) {
    for (size_t i = 0; i < count; i++)
        buf[i] = (u16)((buf[i] << 8) | (buf[i] >> 8));
}

#ifndef A2E_REDUCED_VIDEO
static void plot(a2e_video *v, int x, int y, u8 r, u8 g, u8 b) {
    if ((unsigned)x >= A2E_VIDEO_W || (unsigned)y >= A2E_VIDEO_H) return;
    v->fb[y][x][0] = r;
    v->fb[y][x][1] = g;
    v->fb[y][x][2] = b;
}
#endif

static u8 text_char(a2e_mmu *m, int col, int row) {
    static const u16 LINE[24] = {
        0x000,0x080,0x100,0x180,0x200,0x280,0x300,0x380,
        0x028,0x0A8,0x128,0x1A8,0x228,0x2A8,0x328,0x3A8,
        0x050,0x0D0,0x150,0x1D0,0x250,0x2D0,0x350,0x3D0
    };
    u16 addr = (u16)(0x400 + LINE[row] + col);
    u8 *ram = (m->store80 && m->page2) ? m->aux : m->main;
    if (m->page2 && !m->store80) addr = (u16)(0x800 + LINE[row] + col);
    return ram[addr];
}

static void pixel_text(a2e_mmu *m, int x, int y, u8 *r, u8 *g, u8 *b) {
    int col = x / 7;
    int row = y / 8;
    int gx = x % 7;
    int gy = y % 8;
    if (col < 0 || col >= 40 || row < 0 || row >= 24) {
        *r = *g = *b = 0;
        return;
    }
    u8 ch = text_char(m, col, row);
    bool inv = (ch & 0x80) == 0;
    bool flash = (ch & 0xC0) == 0x40;
    u8 ascii;
    if (ch >= 0xA0) ascii = (u8)(ch & 0x7F);
    else if (ch >= 0x80) ascii = (u8)(ch & 0x7F);
    else if (ch >= 0x40) ascii = (u8)(ch);
    else ascii = (u8)(ch + 0x40);
    if (ascii < 0x20 || ascii > 0x7F) ascii = 0x20;
    const u8 *glyph = FONT_7X8[ascii - 0x20];
    bool on = (glyph[gy] >> (6 - gx)) & 1;
    if (inv || (flash && ((gy + row) & 4))) on = !on;
    if (on) { *r = 0x33; *g = 0xFF; *b = 0x33; }
    else { *r = *g = *b = 0; }
}

static void pixel_hires(a2e_mmu *m, int x, int y, u8 *r, u8 *g, u8 *b) {
    u8 *ram = m->main;
    u16 base = m->page2 ? 0x4000 : 0x2000;
    int group = y >> 3;
    int line = y & 7;
    int blk = group / 8;
    int row = group % 8;
    u16 addr = (u16)(base + line * 0x400 + blk * 0x28 + row * 0x80);
    int byte_i = x / 7;
    int bit = x % 7;
    u8 byte = ram[addr + byte_i];
    u8 on = (byte >> bit) & 1;
    *r = *g = *b = on ? 255 : 0;
}

void a2e_video_render_row_rgb565(a2e_mmu *m, int y, u16 *out) {
    if (!m || !out || y < 0 || y >= A2E_VIDEO_H) return;
    for (int x = 0; x < A2E_VIDEO_W; x++) {
        u8 r, g, b;
        if (m->hires) pixel_hires(m, x, y, &r, &g, &b);
        else pixel_text(m, x, y, &r, &g, &b);
        out[x] = a2e_rgb_to_565(r, g, b);
    }
}

void a2e_video_cyd_panel_row(a2e_mmu *m, int panel_y, u16 *out) {
    if (!out) return;
    for (int x = 0; x < A2E_CYD_PANEL_W; x++) out[x] = 0;
    int ay = panel_y - A2E_CYD_OFF_Y;
    if (ay < 0 || ay >= A2E_VIDEO_H || !m) return;
    u16 apple[A2E_VIDEO_W];
    a2e_video_render_row_rgb565(m, ay, apple);
    memcpy(out + A2E_CYD_OFF_X, apple, A2E_VIDEO_W * sizeof(u16));
}

void a2e_video_render(a2e_video *v, a2e_mmu *m) {
    /* Simplified RGB text/hires (D5) — no NTSC artifact color */
#ifndef A2E_REDUCED_VIDEO
    if (m->hires) {
        for (int y = 0; y < 192; y++) {
            for (int x = 0; x < A2E_VIDEO_W; x++) {
                u8 r, g, b;
                pixel_hires(m, x, y, &r, &g, &b);
                plot(v, x, y, r, g, b);
            }
        }
    } else {
        for (int y = 0; y < A2E_VIDEO_H; y++) {
            for (int x = 0; x < A2E_VIDEO_W; x++) {
                u8 r, g, b;
                pixel_text(m, x, y, &r, &g, &b);
                plot(v, x, y, r, g, b);
            }
        }
    }
#else
    (void)m;
#endif
    v->dirty = false;
}
